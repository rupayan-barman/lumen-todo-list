// Generates public/precache-manifest.js: the list of files the service worker caches
// for offline use, plus a content-hash version so every release gets a fresh cache.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const EXCLUDE = new Set(['sw.js', 'precache-manifest.js']);
const EXCLUDE_EXT = /\.(map|md|log)$/i;

function walk(dir, out = []) {
  for (const name of readdirSync(dir).sort()) {
    const full = join(dir, name);
    const st = statSync(full);
    if (st.isDirectory()) walk(full, out);
    else out.push(full);
  }
  return out;
}

export function buildManifest(publicDir) {
  const files = walk(publicDir)
    .map((f) => ({ full: f, rel: relative(publicDir, f).split(sep).join('/') }))
    .filter((f) => !EXCLUDE.has(f.rel) && !EXCLUDE_EXT.test(f.rel));
  const hash = createHash('sha256');
  const urls = ['./'];
  for (const f of files) {
    hash.update(f.rel);
    hash.update(readFileSync(f.full));
    urls.push('./' + f.rel);
  }
  return { version: hash.digest('hex').slice(0, 12), urls };
}

export function writeManifest(publicDir) {
  const { version, urls } = buildManifest(publicDir);
  const body =
    '// GENERATED by tools/build-precache.mjs - do not edit.\n' +
    `self.PRECACHE_VERSION = ${JSON.stringify(version)};\n` +
    `self.PRECACHE_URLS = ${JSON.stringify(urls, null, 1)};\n`;
  const target = join(publicDir, 'precache-manifest.js');
  let prev = '';
  try { prev = readFileSync(target, 'utf8'); } catch { /* first run */ }
  if (prev !== body) writeFileSync(target, body);
  return { version, count: urls.length, changed: prev !== body };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const publicDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'public');
  const r = writeManifest(publicDir);
  console.log(`Precache manifest: ${r.count} files, version ${r.version}${r.changed ? ' (updated)' : ' (unchanged)'}`);
}
